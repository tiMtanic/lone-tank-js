class EnemyConfig {
  constructor(name, width, height, sprite, deathSprite, health, movementSpeed, attackType) {
    this.name = name;
    this.width = width;
    this.height = height;
    this.sprite = sprite;
    this.deathSprite = deathSprite;
    this.health = health;
    this.movementSpeed = movementSpeed;
    this.attackType = attackType;
  }
}